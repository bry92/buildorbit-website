  // ─── DEMO BUILDER ────────────────────────────────────────────────────────────

  let currentPromptIndex = 0;
  let currentCharIndex = 0;
  let isTyping = false;

  function startTypewriter() {
    const el = document.getElementById('demo-prompt-text');
    if (!el) return;
    if (typewriterInterval) clearInterval(typewriterInterval);

    const prompt = DEMO_PROMPTS[currentPromptIndex % DEMO_PROMPTS.length];
    el.textContent = '';
    currentCharIndex = 0;
    isTyping = true;

    typewriterInterval = setInterval(() => {
      if (currentCharIndex < prompt.length) {
        el.textContent += prompt[currentCharIndex];
        currentCharIndex++;
      } else {
        clearInterval(typewriterInterval);
        isTyping = false;
        setTimeout(() => {
          currentPromptIndex++;
          startTypewriter();
        }, 3000);
      }
    }, 50);
  }

  startTypewriter();

