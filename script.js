  function showPage(pageId) {
    document.querySelectorAll('.page-view').forEach(p => p.classList.add('hidden'));
    const target = document.getElementById('page-' + pageId);
    if (target) {
      target.classList.remove('hidden');
      currentPage = pageId;
      window.scrollTo({ top: 0, behavior: 'smooth' });
    }

    // Update nav active state
    document.querySelectorAll('.nav-link').forEach(btn => {
      btn.classList.remove('text-blue-600', 'bg-blue-50');
      if (btn.dataset.section === pageId) {
        btn.classList.add('text-blue-600', 'bg-blue-50');
      }
    });

    // Close mobile menu
    closeMobileMenu();

    // Page-specific init
    if (pageId === 'blog') renderBlogPosts(currentBlogFilter);
    if (pageId === 'docs') renderDocContent(currentDoc);
    if (pageId === 'dashboard') {
      if (!isLoggedIn) {
        showPage('auth');
        showToast('Please log in to access your dashboard.', 'warning');
        return;
      }
      renderBuildsTable(BUILDS_DATA);
    }
  }

